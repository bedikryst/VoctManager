/**
 * @file foundation.ts
 * @description Who the foundation is, as data: the registered name, the seat, the three registry
 *  numbers and the two accounts. The facts an organiser needs to sign a contract or issue a
 *  transfer, in one place.
 *
 *  IT EXISTS BECAUSE A NUMBER IS NOT PROSE. KRS, NIP and REGON are printed on nine surfaces of
 *  this site and were typed out on every one of them; `docs/specs/web-colophon-remediation.md` records
 *  that as a defect waiting for a registry change to expose it. They are also needed OUTSIDE a
 *  page — the press pack's invoicing sheet is generated by a Node script, which cannot read an
 *  `.astro` template — and that is what finally forced a module: a fact two different runtimes
 *  print has nowhere else to live.
 *
 *  NOT ON THE COPY DESK, AND NOT A CANDIDATE FOR IT. A registry number is not a sentence anybody
 *  reviews or translates; it is identical in all three locales and wrong is wrong in each of them.
 *  The rule the desk draws (§6r — can completeness be demanded) puts it on the same side as a
 *  landmark, and one step further: there is not even a per-locale form.
 *
 *  THE SWEEP IS NOT DONE. Seven display surfaces still carry their own copy of these strings
 *  (SiteFooter ×2, FinalSupportSection, AboutPage, ContactPage, KolofonPage, and the policy /
 *  terms YAML, where the number sits inside a sentence and belongs to the desk). Converting them
 *  is mechanical and is deliberately a separate pass; what this module closed is the one
 *  duplicate that contradicted itself — two files each declaring in their header that they were
 *  the only home of the bank details.
 *
 *  PURE BY CONTRACT. Imported by Astro pages AND by `scripts/press-pack.mjs` under plain Node,
 *  so it stays free of `?raw`, `astro:*` and anything else only a bundler resolves.
 * @architecture Astro islands 2026
 * @module data/foundation
 */

export interface BankAccount {
  /** The IBAN as a bank's field wants it: no spaces, no country prefix stripped. */
  readonly iban: string;
  /** The same number grouped for a human to read and check against a screen. */
  readonly display: string;
  /** Domestic form (NRB) — what a Polish transfer form asks for. */
  readonly nrb: string;
}

export interface Foundation {
  /** As the register carries it — the name that goes on a contract. */
  readonly name: string;
  /** Without the legal form, for a line that already says "Fundacja" beside it. */
  readonly nameShort: string;
  /** The ensemble the foundation runs. A different object from the foundation, on purpose. */
  readonly ensemble: string;
  readonly seat: {
    readonly street: string;
    readonly postalCode: string;
    readonly city: string;
    readonly countryCode: "PL";
  };
  /** The seat as one line, which is how every surface actually prints it. */
  readonly addressLine: string;
  readonly registry: {
    readonly krs: string;
    readonly nip: string;
    readonly regon: string;
  };
  readonly accounts: {
    readonly pln: BankAccount;
    /** A second account in EUR. It exists for a foreign organiser and for nothing else. */
    readonly eur: BankAccount;
  };
  readonly mail: {
    readonly booking: string;
    readonly general: string;
    readonly patronage: string;
    readonly director: string;
  };
  readonly site: string;
}

