const BY_LOWERCASE_NAME: ReadonlyMap<string, string> = new Map(
  Object.entries(VOCATIVES).map(([name, vocative]) => [
    name.toLocaleLowerCase("pl"),
    vocative,
  ]),
);

/**
 * The vocative the table holds for the first word of `firstName`, or "" when
 * it holds none. Only the first word is looked up: "Michał Jan" is greeted as
 * Michał. A hyphenated name is one word and, unlisted, yields "".
 */
export const vocativeFromTable = (firstName: string): string => {
  const [given = ""] = firstName.trim().split(/\s+/);
  return BY_LOWERCASE_NAME.get(given.toLocaleLowerCase("pl")) ?? "";
};
